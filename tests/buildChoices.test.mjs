test('Human origin feats and background feat follow-up choices are required and saved', () => {
  const character = hero('Wizard'); character.species = 'Human'; character.background = 'Sage';
  assert.ok(startingChoiceErrors(character, {}).some(error => /Origin feat/.test(error)));
  const values = { 'Human:origin-feat': ['Tough'], 'Origin:magic-0-ability': ['Intelligence'], 'Origin:magic-0-spells-0': ['Light', 'Mending'], 'Origin:magic-0-spells-1': ['Magic Missile'] };
  assert.deepEqual(startingChoiceErrors(character, values), []);
  assert.ok(applyStartingChoices(character, values).features.some(feature => feature.name === 'Tough' && feature.category === 'feat'));
  const changed = { ...values, 'Human:origin-feat': ['Skilled'], 'Origin:skilled': ['Arcana', 'History', 'Religion'] };
  assert.equal(applyStartingChoices(character, changed).skillProficiencies.Arcana, 1);
  const cleaned = pruneChoices({ ...changed, 'Warlock:tome-cantrips': ['Guidance'] }, startingClassChoices(character, changed));
  assert.ok(!('Warlock:tome-cantrips' in cleaned));
  assert.deepEqual(cleaned['Origin:skilled'], ['Arcana', 'History', 'Religion']);
});
